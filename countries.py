def get_currency_by_country(country_name: str) -> str | None:
    """Найти код валюты по названию страны (без учёта регистра)"""
    return COUNTRIES_TO_CURRENCY.get(country_name.lower().strip())


def get_currency_name(currency_code: str) -> str:
    """Получить читаемое название валюты по коду"""
    return CURRENCY_NAMES.get(currency_code.upper(), currency_code)
